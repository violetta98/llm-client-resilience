"""Build the public GitHub copy of this repository in a separate folder, without changing anything here.

  python3 tools/build_public.py [--out ../llm-client-resilience]

Copies
  - the working tree (git-tracked and untracked, not ignored), except data/, dist/, reports/ (internal stage reports
    for the author), STATUS.md, README.md and .gitignore, whose public versions live in the target folder and are
    written by hand (they are never overwritten here);
  - summary data into data/: programs.csv, runs.csv, primary.csv and features.csv of the main run, runs.csv of the
    repeatability run, coverage.json, the paper tables (analysis/out/main/paper/) into data/tables/, and the library
    baselines (table_ix.csv, baselines_raw.json, sync_calibration.json) into data/baselines/;
  - the other small result files of analysis/out/main/ into data/results/, the sensitivity outputs of D33 into
    data/sensitivity_noresult_as_returned/, and the output map analysis/out/README.md (the only file of
    analysis/out/ that is committed);
  - figures into figures/ (numbered as in the paper) and environment snapshots (incl. `docker version` and the R
    package list of the analysis image) into reports/env/;
  - the summary outputs of the repair experiment (analysis/out/repair/) into data/repair/, of the confirmatory
    replication (analysis/out/confirm/) into data/confirm/, and of the variant runs and exploratory analyses into
    data/variants/ and data/exploratory/.
Generated paths of an earlier layout (STALE) are removed from the target first; hand-written files are never touched.
Development documents are not in the public copy (as in the author's earlier replication repository, git keeps only
reports/results.md): RUNBOOK.md, reports/RUNLOG.md and reports/TESTBED.md of this repository, the log of `make analyze`
and the other files of analysis/out/ go to the Zenodo code archive (tools/package_zenodo.py). Exact duplicates of
files already in data/ (data/results/primary.csv, programs.csv) and of gen/config/main.json are not written.
Every text file is passed through tools/package_zenodo.clean(), which replaces the absolute path of this checkout by
`<repo>`, the home directory by `<home>` and the host name by `<host>`. Everything else under analysis/out/ is
regenerated by `make analyze`. __pycache__ directories left in the target by earlier test runs are removed.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from package_zenodo import REPO, clean  # noqa: E402

SKIP_TOP = ("data/", "dist/", "reports/", "analysis/out/")
SKIP_FILES = {"STATUS.md", "README.md", ".gitignore", "RUNBOOK.md", "tools/make_check_page.py", "tools/make_hard_cases.py",
              "gen/README.md", "docs_examples/README.md"}  # check pages: author-only; the two READMEs are summarized in the public README
OUT_MAIN = REPO / "analysis" / "out" / "main"

EXTRA = {
    "data/programs.csv": OUT_MAIN / "programs.csv",
    "data/runs.csv": OUT_MAIN / "runs.csv",
    "data/primary.csv": OUT_MAIN / "primary.csv",
    "data/features.csv": REPO / "data" / "main" / "classify" / "features.csv",
    "data/classify_agreement.csv": REPO / "analysis" / "out" / "classify_agreement.csv",
    "data/rep-runs.csv": REPO / "analysis" / "out" / "main-rep" / "runs.csv",
    "data/coverage.json": OUT_MAIN / "coverage.json",
    "data/baselines/table_ix.csv": REPO / "analysis" / "out" / "table_ix.csv",
    "data/baselines/baselines_raw.json": REPO / "analysis" / "out" / "baselines_raw.json",
    "data/baselines/sync_calibration.json": REPO / "analysis" / "out" / "sync_calibration.json",
    "figures/figE1_km.png": OUT_MAIN / "fig_km.png",
    "figures/figE1_km.pdf": OUT_MAIN / "fig_km.pdf",
    "figures/figE2_dumbbell.pdf": OUT_MAIN / "fig_dumbbell.pdf",
    "figures/figE2_dumbbell.png": OUT_MAIN / "fig_dumbbell.png",
    "figures/fig3_s4construct.pdf": OUT_MAIN / "fig_s4construct.pdf",
    "figures/fig3_s4construct.png": OUT_MAIN / "fig_s4construct.png",
    "reports/env/lint_versions.json": REPO / "data" / "main" / "lint" / "versions.json",
    "analysis/out/README.md": REPO / "analysis" / "out" / "README.md",
}
BIG = {"runs.csv", "runs.jsonl"}  # already in data/ (runs.csv) or rebuilt from the raw data (runs.jsonl)
DUP = {"primary.csv", "programs.csv"}  # analysis/out/main/ copies of data/primary.csv and data/programs.csv
OUT_REPAIR = REPO / "analysis" / "out" / "repair"
# generated paths of the earlier (IEEE-era) layout, removed from the target before writing
STALE = ("env", "verification", "RUNBOOK.md", "figures/fig2_km.png", "figures/fig2_km.pdf", "figures/fig3_km.png", "figures/fig3_km.pdf",
         "figures/fig4_dumbbell.pdf", "figures/fig4_dumbbell.png", "figures/fig_s4construct.pdf", "figures/fig_s4construct.png", "data/tables",
         # development documents and duplicates, no longer in the public copy (kept in this repository / on Zenodo)
         "reports/RUNBOOK.md", "reports/RUNLOG.md", "reports/TESTBED.md", "reports/verification",
         "reports/env/generation_config.json", "data/results/primary.csv", "data/results/programs.csv",
         # 2026-11-22: duplicate or internal Markdown (table_ix.md = table_ix.csv; table_i_check.md is a stage check)
         "data/baselines/table_ix.md", "data/baselines/table_i_check.md", "gen/README.md", "docs_examples/README.md")


def put(dst: Path, data: bytes):
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_bytes(clean(data))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(REPO.parent / "llm-client-resilience"))
    a = ap.parse_args()
    out = Path(a.out).resolve()
    if out == REPO or REPO in out.parents:
        sys.exit("target must be outside this repository")
    out.mkdir(parents=True, exist_ok=True)
    for s in STALE:
        p = out / s
        if p.is_dir():
            shutil.rmtree(p)
        elif p.exists():
            p.unlink()

    ls = subprocess.run(["git", "ls-files", "-co", "--exclude-standard", "-z"], cwd=REPO, capture_output=True,
                        check=True).stdout.decode().split("\0")
    code = sorted(f for f in ls if f and not f.startswith(SKIP_TOP) and f not in SKIP_FILES and (REPO / f).is_file()
                  and "__pycache__" not in f)
    for rel in code:
        put(out / rel, (REPO / rel).read_bytes())
        shutil.copymode(REPO / rel, out / rel)
    # data/SCHEMA.md (raw-file schema) ships only with the Zenodo data record, as in the earlier replication package

    for rel, src in EXTRA.items():
        put(out / rel, src.read_bytes())
    # D59: the author's blind labels of the classifier sample, labels only (the author's working notes are not released)
    import csv as _csv
    import io as _io
    rows = list(_csv.DictReader(open(REPO / "data" / "main" / "classify" / "manual_check.csv", encoding="utf-8")))
    cols = [c for c in rows[0] if c != "author_note"]
    buf = _io.StringIO()
    w = _csv.DictWriter(buf, cols, extrasaction="ignore", lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    put(out / "data" / "manual_check.csv", buf.getvalue().encode("utf-8"))
    # D60: verdicts of the author's run, code and hard-case checks, without the working notes
    for name, keep in (("audit_runs.csv", ("id", "label", "run", "verdict")), ("audit_code.csv", ("item", "verdict")),
                       ("hard_cases.csv", ("id", "group", "case", "verdict"))):
        src = REPO / "reports" / "manual_check" / "author_results" / name
        rows = list(_csv.DictReader(open(src, encoding="utf-8")))
        buf = _io.StringIO()
        w = _csv.DictWriter(buf, list(keep), extrasaction="ignore", lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
        put(out / "data" / "manual_checks" / name, buf.getvalue().encode("utf-8"))
    for f in sorted((OUT_MAIN / "paper").glob("table*.csv")):
        put(out / "data" / "tables" / f.name, f.read_bytes())
    for f in sorted(OUT_MAIN.glob("*.csv")):
        if f.name not in BIG | DUP:
            put(out / "data" / "results" / f.name, f.read_bytes())
    for f in sorted(OUT_REPAIR.glob("*")):
        if f.is_file() and f.name not in BIG:
            put(out / "data" / "repair" / f.name, f.read_bytes())
    # D43 confirmatory replication and the variant runs (D38, D39, D45)
    for f in sorted((REPO / "analysis" / "out" / "confirm").glob("*")):
        if f.is_file() and f.name not in BIG:
            put(out / "data" / "confirm" / f.name, f.read_bytes())
    put(out / "data" / "confirm" / "features.csv", (REPO / "data" / "confirm" / "classify" / "features.csv").read_bytes())
    # D51-D53: prompt ablation, JDK 26 reruns, hand-written advice programs (only the outputs that exist)
    for run in ("ablation", "confirm-s56", "main-jdk26", "confirm-jdk26", "repair-jdk26", "jdk26b", "review10", "review11", "review12", "ablation-jdk26", "advice", "advice-ra30", "advice-ra30b", "advice-slow", "advice-ra30c", "advice-slow2", "review13", "main-jdk26-hybrid", "robustness", "deadline_v2", "docs", "precision", "human-pypi"):
        for f in sorted((REPO / "analysis" / "out" / run).glob("*")):
            if f.is_file() and f.name not in BIG:
                put(out / "data" / run / f.name, f.read_bytes())
    # D64: package list of the human-code comparison (sources are third-party and not copied)
    put(out / "data" / "human-pypi" / "packages.csv", (REPO / "data" / "human-pypi" / "packages.csv").read_bytes())
    for f in sorted((REPO / "advice").rglob("*.*")):
        put(out / "advice" / f.relative_to(REPO / "advice"), f.read_bytes())
    for sub in ("variants", "exploratory", "review"):
        for f in sorted((OUT_MAIN / sub).glob("*")):
            if f.is_file():
                put(out / "data" / sub / f.name, f.read_bytes())
    for f in sorted((OUT_MAIN / "sensitivity_noresult_as_returned").glob("*")):
        put(out / "data" / "sensitivity_noresult_as_returned" / f.name, f.read_bytes())
    dv = subprocess.run(["docker", "version"], capture_output=True, text=True)
    put(out / "reports" / "env" / "docker_version.txt", dv.stdout.encode())
    rp = subprocess.run(["docker", "run", "--rm", "--network", "none", "lcr-analysis-r:dev", "cat",
                         "/etc/lcr-r-packages.tsv"], capture_output=True, text=True)
    if rp.returncode == 0:
        put(out / "reports" / "env" / "r_packages.tsv", rp.stdout.encode())
    for pc in sorted(out.rglob("__pycache__"), reverse=True):
        shutil.rmtree(pc)
    with zipfile.ZipFile(REPO / "dist" / "protocol-v1.zip") as z:
        put(out / "reports" / "env" / "environment.json", z.read("protocol-v1/environment.json"))
    print(f"{len(code)} code files and {len(EXTRA)} data files written to {out}")


if __name__ == "__main__":
    main()
