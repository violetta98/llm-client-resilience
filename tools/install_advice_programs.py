"""D52: copy the advice-check programs of advice/<task>/<name>.<ext> into the generation layout of run `advice`
(data/advice/generations/ADV/<name>/<task>/<lang>/1/solution.<ext> + meta.json), so that runner/run_generated.py
prepares and runs them like generated solutions. Written by hand for this check, not generated by a model.

  python3 tools/install_advice_programs.py && python3 runner/run_generated.py --run advice --scenarios S0,S4,S5a,S8 --no-rerun --slots 3
"""
import json
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LANG = {"py": "python", "ts": "typescript", "java": "java", "go": "go"}
n = 0
for f in sorted((REPO / "advice").glob("*/*.*")):
    task, name, ext = f.parent.name, f.stem, f.suffix[1:]
    if not (REPO / "tasks" / task).is_dir():  # e.g. advice/gzip_check (D54), not a task program
        continue
    d = REPO / "data" / "advice" / "generations" / "ADV" / name / task / LANG[ext] / "1"
    d.mkdir(parents=True, exist_ok=True)
    shutil.copy(f, d / f"solution.{ext}")
    (d / "meta.json").write_text(json.dumps({"status": "ok", "model_id": name, "note": "hand-written advice check (D52)",
                                             "extraction": {"status": "fenced", "n_blocks": 1, "n_target_blocks": 1}}, indent=1))
    n += 1
print(n, "programs installed")
