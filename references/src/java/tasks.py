BODIES["R3"] = exc("Download") + '''
    /** Streams into a per-attempt temporary file; only a complete download is moved to destPath. */
    public static int downloadReport(String baseUrl, String reportId, String destPath) throws DownloadException {
        List<Path> parts = new ArrayList<>();
        String url = baseUrl + "/v1/reports/" + enc(reportId) + "/download";
        try {
            Resp r = call(deadlineIn(9500), true, a -> HttpRequest.newBuilder(URI.create(url)).GET(),
                info -> {
                    Path part = Path.of(destPath + ".part" + parts.size());
                    parts.add(part);
                    return info.statusCode() == 200 ? HttpResponse.BodySubscribers.ofFile(part)
                        : HttpResponse.BodySubscribers.replacing(part);
                });
            if (r.status() != 200) throw new DownloadException("HTTP " + r.status());
            Path part = parts.get(parts.size() - 1);
            long size = Files.size(part);
            String cl = r.headers().firstValue("Content-Length").orElse(null);
            if (cl != null && Long.parseLong(cl) != size) throw new DownloadException("incomplete body");
            Files.move(part, Path.of(destPath), StandardCopyOption.REPLACE_EXISTING);
            return (int) size;
        } catch (GiveUp | IOException | InterruptedException e) {
            throw new DownloadException(String.valueOf(e), e);
        } finally {
            for (Path p : parts) { try { Files.deleteIfExists(p); } catch (IOException ignored) { } }
        }
    }
'''

