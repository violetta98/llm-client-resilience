def assemble(task, prelude, mutant):
    imps = sorted(set(PRELUDE_IMPORTS) | set(IMPORTS.get(task, [])))
    head = f"// Reference solution {task} (Go), MUTANT={mutant}. Generated by references/build.py; do not edit.\npackage main\n\nimport (\n"
    head += "".join(f'\t{i}\n' if " " in i else f'\t"{i}"\n' for i in imps) + ")\n\n"
    return head + prelude.replace("{{MUTANT}}", mutant) + BODIES[task]


