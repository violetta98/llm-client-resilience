"""Assembles reference solutions and mutants from references/src/<lang>/.

references/<ID>/<lang>/solution.<ext>          MUTANT = NONE
mutants/<ID>/<lang>/<MUTANT>/solution.<ext>    one property removed (draft IV-F)

A mutant differs from its reference only in the value of the MUTANT constant,
which switches exactly one policy in the shared prelude (see references/README.md).
"""
import importlib.util
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "references" / "src"
EXT = {"python": "py", "go": "go", "typescript": "ts", "java": "java"}
MUTANTS = ["NO_TIMEOUT", "TIGHT_LOOP", "IGNORE_RETRY_AFTER", "UNSAFE_POST_RETRY", "FIXED_BACKOFF"]
UNSAFE_TASKS = {"W1", "W2"}  # B4: the receiver deduplicates by the event id in the given event (N/A, README)
MUTANT_TASKS = {"python": None, "go": None, "typescript": ["R1", "W1", "B2", "H3"], "java": ["R1", "W1", "B2", "H3"]}
TASKS = ["R1", "R2", "R3", "R4", "R5", "W1", "W2", "W3", "W4", "B1", "B2", "B3", "B4", "H1", "H2", "H3"]


PILOT_TASKS = ["P1", "P2", "P3"]  # outside the benchmark (tasks/pilot_catalog.py); no mutants


def load(lang, pilot=False):
    spec = importlib.util.spec_from_file_location(f"src_{lang}", SRC / lang / "tasks.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    if pilot:
        exec((SRC / lang / "pilot_tasks.py").read_text(), m.__dict__)
    return m


def render(lang, task, mutant, mod):
    prelude = (SRC / lang / f"prelude.{EXT[lang]}").read_text()
    return mod.assemble(task, prelude, mutant) if hasattr(mod, "assemble") else \
        f"# Reference solution {task} (Python), MUTANT={mutant}. Generated by references/build.py; do not edit.\n" \
        + prelude.replace("{{MUTANT}}", mutant) + mod.BODIES[task]


def applicable(task, mutant):
    return mutant != "UNSAFE_POST_RETRY" or task in UNSAFE_TASKS


def main(langs):
    pilot = "--pilot" in langs
    langs = [x for x in langs if x != "--pilot"]
    if pilot:
        return main_pilot(langs)
    index = []
    for lang in langs:
        mod = load(lang)
        for t in TASKS:
            if t not in getattr(mod, "BODIES", {}) and not hasattr(mod, "assemble"):
                continue
            out = REPO / "references" / t / lang / f"solution.{EXT[lang]}"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(render(lang, t, "NONE", mod))
            index.append({"task": t, "lang": lang, "variant": "REFERENCE", "path": str(out.relative_to(REPO))})
            if MUTANT_TASKS[lang] is None or t in MUTANT_TASKS[lang]:
                for m in MUTANTS:
                    if not applicable(t, m):
                        continue
                    out = REPO / "mutants" / t / lang / m / f"solution.{EXT[lang]}"
                    out.parent.mkdir(parents=True, exist_ok=True)
                    out.write_text(render(lang, t, m, mod))
                    index.append({"task": t, "lang": lang, "variant": m, "path": str(out.relative_to(REPO))})
    (REPO / "references" / f"index-{'-'.join(langs)}.json").write_text(json.dumps(index, indent=1))
    print(f"{len(index)} programs")


def main_pilot(langs):
    index = []
    for lang in langs:
        mod = load(lang, pilot=True)
        for t in PILOT_TASKS:
            out = REPO / "pilot" / "references" / t / lang / f"solution.{EXT[lang]}"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(render(lang, t, "NONE", mod))
            index.append({"task": t, "lang": lang, "variant": "REFERENCE", "path": str(out.relative_to(REPO))})
    (REPO / "pilot" / "references" / "index.json").write_text(json.dumps(index, indent=1))
    print(f"{len(index)} pilot programs")


if __name__ == "__main__":
    main(sys.argv[1:] or ["python"])
